#pragma once

#include "xuyan/domain/scenario.h"

#include <filesystem>
#include <string>

namespace xuyan::application {

/*
 * 备份/恢复成功结果，由同步操作生成并交调用方独立持有，无文件句柄或借用引用。
 * 仅记录数据库路径和资产统计；路径可能暴露本地目录，不能当作脱敏诊断直接上传。
 * 该对象不持有正文，但对应备份本身包含数据库和资产中的用户资料。
 */
struct BackupReport {
    /* 数据库文件路径，无数值单位；默认空。服务在构建结果及发布目标时填写，成功返回后由调用方读取；不拥有文件。 */
    std::filesystem::path workspace_database;
    /* 本次复制的普通资产文件数，单位个，默认 0，成功值不超过 10000；服务逐文件累计，调用方读取；不含目录、数据库及清单。 */
    int asset_count{0};
    /* 本次资产总量，单位字节，默认 0，成功值不超过 4 GiB；服务累计，调用方读取。创建按文件元数据计数，恢复按实际读入字节计数。 */
    std::uintmax_t asset_bytes{0};
};

/*
 * 工作区数据库与资产的备份/恢复入口，拥有源数据库路径值，不持有连接、线程或系统凭据。
 * 每次创建备份临时打开仓储，恢复只复制经清单校验的文件；局部流和连接在调用结束时释放。
 * 全部操作在调用线程同步执行，无取消接口或跨线程锁；调用方负责源资产稳定及目标目录独占。
 * 源数据库与资产不在同一快照中；备份不加密、不过滤数据库或资产内自行保存的敏感内容。
 */
class BackupService {
public:
    /*
     * 功能：保存以后创建备份所用的数据库路径，不立即验证或打开源工作区。
     * 参数：database_path：输入，按值接收后移入成员；父目录下的 assets 为资产根。
     *   无默认值，空路径不在构造时拒绝；建议使用明确的绝对路径，相对路径随调用时工作目录解析。
     * 返回：无返回值；完成路径初始化。
     * 失败：参数复制或路径初始化的异常向调用方传播。
     * 副作用：不访问文件、数据库、网络或凭据。
     * 线程与生命周期：调用线程同步构造；路径与服务同寿命，不保留调用方对象引用。
     */
    explicit BackupService(std::filesystem::path database_path);
    /*
     * 功能：将 SQLite 在线快照、可遍历的普通资产及 SHA-256 清单写入同级暂存目录，再重命名发布备份。
     * 参数：destination_directory：输入，只借用至返回；无默认值，须非空且尚不存在。
     *   调用方须独占目标及同级暂存范围，并选择源 assets 树外的目标；实现不校验源/目标包含关系。
     * 返回：成功 Result 含目标下 workspace.sqlite 路径、资产数和总字节数；无 assets 目录仍可成功，统计为 0。
     * 失败：目标无效、数据库快照、路径、摘要或文件操作失败转为 storage_error；遍历到的符号链接拒绝。
     *   资产单文件上限 128 MiB、合计 4 GiB、最多 10000 个，数据库读入上限 2 GiB。
     *   无权限目录允许跳过，非普通文件跳过，不承诺全部资产均被复制；生成暂存路径位于 try 外，异常可传播。
     * 副作用：建父/暂存目录并复制用户数据库、小说资产等；打开源仓储可能创建数据库及迁移结构。
     *   捕获异常后仅对计算所得暂存路径 remove_all，清理错误忽略；已发布目标不在回滚范围内。
     *   不读取系统凭据，但不检测文件内容中的秘密，也不加密备份。
     * 线程与生命周期：调用线程同步执行，无取消或异步回调；输入路径不保存。
     *   SQLite 快照与后续资产复制分开执行，调用方须保持源资产不变；文件哈希通过整文件读入计算。
     */
    xuyan::domain::Result<BackupReport> create(const std::filesystem::path& destination_directory);
    /*
     * 功能：核对清单协议、路径和文件摘要，将数据库及清单列出的资产复制到暂存目录，再重命名发布。
     * 参数：
     *   backup_directory：输入，调用期间只读借用的备份根目录，无默认值；必须能读取 manifest.json。
     *   destination_directory：输入，借用至返回的新工作区目录，无默认值；应非空且尚不存在、位于备份源树外。
     *   调用方须保证源及中间目录可信且稳定、目标及暂存范围独占；实现不做包含关系或完整符号链接链校验。
     * 返回：成功 Result 含目标数据库路径及实际复制的资产统计；空资产数组成功返回 0 计数。
     * 失败：源不是目录、目标已存在，或清单格式/版本/凭据标记、重复/非法资产路径、摘要及文件操作错误返回 storage_error。
     *   清单上限 4 MiB、数据库 2 GiB、资产单文件 128 MiB、合计 4 GiB、最多 10000 个；不核对清单 size 字段。
     *   只检查清单、数据库及资产最终路径是否为符号链接，不验证 SQLite 可打开性；空目标无单独校验。
     *   暂存路径在 try 外生成，其异常可传播。
     * 副作用：创建父/暂存目录并复制用户资料；只恢复清单列出的文件，不恢复系统凭据。
     *   credentials_included 必须为 false，但该标记不证明资产或数据库内容无秘密；捕获异常后尽力递归清理暂存路径，忽略清理错误。
     *   重命名后的目标不在失败回滚范围内，失败不能保证完全没有落盘文件。
     * 线程与生命周期：调用线程同步执行，无线程、回调或取消；不保留输入引用，文件流在局部作用域关闭。
     */
    static xuyan::domain::Result<BackupReport> restore(
        const std::filesystem::path& backup_directory, const std::filesystem::path& destination_directory);
private:
    /* 源数据库路径值，无数值单位、无成员默认值；由构造参数初始化，空值不提前校验。create 只读，资产根取父目录/assets；随服务释放，不持有连接。 */
    std::filesystem::path database_path_;
};

} // namespace xuyan::application
